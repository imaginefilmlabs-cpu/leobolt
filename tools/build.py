#!/usr/bin/env python3
"""Rebuild the clip data in index.html from clips.json.

Reads each clip's real aspect ratio from wall/<id>.mp4, checks every clip has
its .mp4 and .webp, and rewrites the CLIPS / CATN / ORDER block in index.html.
Usage: python3 tools/build.py
"""
import json, re, subprocess, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CATS = {"film": "AI Film", "music": "Music Video", "product": "Product Film",
        "anim": "Animation", "vfx": "AI VFX", "narra": "Narramatic", "earlier": "Earlier Work"}

data = json.loads((ROOT / "clips.json").read_text())
errors, clips, order = [], {}, []
for c in data["clips"]:
    cid = c["id"]
    mp4, webp = ROOT / "wall" / f"{cid}.mp4", ROOT / "wall" / f"{cid}.webp"
    if c["category"] not in CATS: errors.append(f"{cid}: unknown category {c['category']}")
    if not mp4.exists(): errors.append(f"{cid}: missing {mp4.name}")
    if not webp.exists(): errors.append(f"{cid}: missing {webp.name}")
    if cid in clips: errors.append(f"{cid}: listed twice")
    if errors: continue
    wh = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries",
                         "stream=width,height", "-of", "csv=p=0", str(mp4)],
                        capture_output=True, text=True).stdout.strip()
    w, h = map(int, wh.split(",")[:2])
    full = c.get("full", "")
    if full and not (ROOT / full).exists(): errors.append(f"{cid}: missing full film {full}"); continue
    clips[cid] = [c["label"], c["category"], round(w / h, 4), c.get("stamp", ""), 1 if c.get("india") else 0]
    if full: clips[cid].append(full)
    order.append(cid)
if errors:
    sys.exit("Build stopped:\n  " + "\n  ".join(errors))

block = ("  /* clip id: [technique label, category, aspect w/h, camcorder stamp, india, full film (optional)] — generated by tools/build.py from clips.json */\n"
         f"  var CLIPS={json.dumps(clips, ensure_ascii=False)};\n"
         f"  var CATN={json.dumps(CATS, ensure_ascii=False)};\n"
         f"  var ORDER={json.dumps(order)};\n")
p = ROOT / "index.html"
s = p.read_text()
s2, n = re.subn(r"  /\* clip id: .*?\n  var ORDER=\[.*?\];\n", lambda m: block, s, flags=re.S)
if n != 1:
    sys.exit("Build stopped: could not find the clip block in index.html")
p.write_text(s2)

used = set(order)
orphans = sorted(f.stem for f in (ROOT / "wall").glob("*.mp4") if f.stem not in used)
counts = {k: sum(1 for c in clips.values() if c[1] == k) for k in CATS}
print(f"Built {len(order)} clips  " + "  ".join(f"{k}:{v}" for k, v in counts.items()) +
      f"  india:{sum(c[4] for c in clips.values())}")
if orphans:
    print("Unused files in wall/ (not on the page):", ", ".join(orphans))
